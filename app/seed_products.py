async def ensure_products() -> int:
    async with async_session_maker() as session:
        existing = set((await session.exec(select(Product.sku))).all())
        added = 0
        for item in PRODUCTS:
            if item["sku"] in existing:
                continue
            session.add(Product(**item))
            added += 1
        if added:
            await session.commit()
        return added
